#include <bits/stdc++.h>
using namespace std;

long long t;

int main()
{
	int n;
	cin >> n;

	if (n <= 9) cout << n;
	else if (n <= 99) cout << 9 + 2 * (n - 9);
	else if (n <= 999) cout << 9 + 180 + 2700 + 3 * (n - 99);
	else if (n <= 9999) cout << 9 + 180 + 2700 + 36000 + 4 * (n - 999);
	else if (n <= 99999) cout << 9 + 180 + 2700 + 36000 + 450000 + 5 * (n - 9999);
	else if (n <= 999999) cout << 9 + 180 + 2700 + 36000 + 450000 + 5400000 + 6 * (n - 99999);
	else if (n <= 9999999)
	{
		t = 9 + 180 + 2700 + 36000 + 450000 + 5400000 + 63000000 + 7 * (n - 999999);
		cout << t; 
	}
	else if (n <= 99999999) 
	{
		t = 9 + 180 + 2700 + 36000 + 450000 + 5400000 + 63000000 + 720000000 + 8 * (n - 9999999);
		cout << t;
	}
	else if (n <= 999999999) 
	{
		t = 9 + 180 + 2700 + 36000 + 450000 + 5400000 + 63000000 + 720000000 + 8100000000 + 9 * (n - 99999999);
		cout << t;
	}
	else if (n == 1000000000) 
	{
		t = 19 + 180 + 2700 + 36000 + 450000 + 5400000 + 63000000 + 720000000 + 8100000000;
		cout << t;
	}
	return 0;
}