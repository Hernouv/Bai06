#include <bits/stdc++.h>
using namespace std;

bool check[1000010];
long long sumfact[1000010];
void setVal()
{
    sumfact[1] = 0;
    for (int i = 2; i <= 1000000; ++i)
        sumfact[i] = 1;
    for (int i = 2; i <= 500000; ++i)
        for (int j = 2 * i; j <= 1000000; j += i)
            sumfact[j] += i;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAC4.INP", "r", stdin);
    freopen("MAC4.OUT", "w", stdout);
    setVal();
    long long a, b, cnt = 0;
    cin >> a >> b;
    for (int i = a; i <= b; ++i)
    {
        if (!check[i])
        {
            check[i] = true;
            long long partner = sumfact[i];
            if (sumfact[i] == partner and sumfact[partner] == i and partner <= b)
            {
                cnt++;
                check[partner] = true;
            }
        }
    }
    cout << cnt;
    return 0;
}
