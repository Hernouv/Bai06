#include <bits/stdc++.h>
using namespace std;

bool erastos[1000010];
long long primefactmul[1000010];
unordered_map<long long, long long> similar_pair;

void sieve()
{
    memset(erastos, true, sizeof(erastos));
    erastos[0] = erastos[1] = false;
    for (int i = 2; i <= 1000; ++i)
        if (erastos[i])
            for (int j = i * i; j <= 1000000; j += i)
                erastos[j] = false;
}

void setVal()
{
    primefactmul[0] = primefactmul[1] = 0;
    for (int i = 2; i <= 1000000; ++i)
        primefactmul[i] = 1;
    for (int i = 2; i <= 1000000; ++i)
        if (erastos[i])
            for (long long j = i; j <= 1000000; j += i)
                primefactmul[j] *= i;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAC5.INP", "r", stdin);
    freopen("MAC5.OUT", "w", stdout);
    sieve();
    setVal();
    long long a, b, res = 0;
    cin >> a >> b;
    for (int i = a; i <= b; ++i)
        similar_pair[primefactmul[i]]++;
    for (auto x : similar_pair)
    {
        if (x.second > 1)
        {
            long long num = x.second;
            res += (num * (num - 1)) >> 1;
        }
    }
    cout << res;
    return 0;
}
