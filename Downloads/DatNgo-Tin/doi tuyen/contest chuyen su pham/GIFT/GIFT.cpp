#include <bits/stdc++.h>
using namespace std;

long long n, k;
long long val[1000010];
long long mod[1000010];
vector<long long> modcnt[1000010];
bool valid = false;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("GIFT.INP", "r", stdin);
    freopen("GIFT.OUT", "w", stdout);
    cin >> n >> k;
    for (int i = 1; i <= n; ++i)
        cin >> val[i];
    mod[0] = 0;
    for (int i = 1; i <= n; ++i)
    {
        mod[i] = (mod[i - 1] + val[i]) % k;
        modcnt[mod[i]].push_back(i);
        if (modcnt[mod[i]].size() > 1)
        {
            valid = true;
            for (int j = modcnt[mod[i]][0] + 1; j <= i; ++j)
                cout << j << ' ';
            break;
        }
        else if (!mod[i])
        {
            valid = true;
            for (int j = 1; j <= i; ++j)
                cout << j << ' ';
            break;
        }
    }
    if (!valid)
        cout << 0;
    return 0;
}
