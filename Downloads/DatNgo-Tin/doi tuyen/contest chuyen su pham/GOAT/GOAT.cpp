#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("GOAT.INP", "r", stdin);
    freopen("GOAT.OUT", "w", stdout);
    int q;
    cin >> q;
    for (int i = 1; i <= q; ++i)
    {
        int n;
        cin >> n;
        if (n % 10)
            cout << "SIUU" << '\n';
        else
            cout << "BOBO" << '\n';
    }
    return 0;
}
