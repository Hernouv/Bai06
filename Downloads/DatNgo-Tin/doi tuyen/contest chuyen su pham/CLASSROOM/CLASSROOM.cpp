#include <bits/stdc++.h>
using namespace std;

const long long mod = 1e9 + 7;
long long cmod[50010];
long long res;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("CLASSROOM.INP", "r", stdin);
    freopen("CLASSROOM.OUT", "w", stdout);
    int m, n, t;
    cin >> t;
    for (int i = 1; i <= t; ++i)
    {
        res = 0;
        memset(cmod, 0, sizeof(cmod));
        cin >> m >> n;
        n++;
        cmod[0] = 1;
        for (long long j = 1; 2 * j < n; ++j)
        {
            cmod[j] = cmod[j - 1] * (n - j) / j;
            cmod[j] %= mod;
        }
        if (n & 1)
        {
            int it = n >> 1;
            cmod[it] = cmod[it - 1] * (n - it) / it;
            cmod[it] %= mod;
        }
        n--;
        for (int j = 0; j <= m; ++j)
        {
            if (2 * j < n)
                res += cmod[j];
            else
                res += cmod[n - j];
            res %= mod;
        }
        cout << res << '\n';
    }
    return 0;
}
