#include <bits/stdc++.h>
using namespace std;

long long sumfact[100010];

void setVal()
{
    for (int i = 1; i <= 100000; ++i)
        sumfact[i] = 1;
    for (int i = 2; i <= 50000; ++i)
    {
        for (int j = 2 * i; j <= 100000; j += i)
            sumfact[j] += i;
    }
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB4.INP", "r", stdin);
    freopen("MAB4.OUT", "w", stdout);
    setVal();
    int a, b, cnt = 0;
    cin >> a >> b;
    for (int i = a; i <= b; ++i)
        if (sumfact[i] > i)
            cnt++;
    cout << cnt;
    return 0;
}
