#include <bits/stdc++.h>
using namespace std;

long long integer = 1, inroot = 1;
long long inp;
unordered_map<long long, long long> expo;

long long power(long long base, long long exp)
{
    long long ret = 1;
    for (long long i = 1; i <= exp; ++i)
        ret *= base;
    return ret;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB7.INP", "r", stdin);
    freopen("MAB7.OUT", "w", stdout);
    cin >> inp;
    for (int i = 2; i * i <= inp; ++i)
    {
        if (inp % i == 0)
        {
            while (inp % i == 0)
            {
                expo[i]++;
                inp /= i;
            }
        }
    }
    if (inp > 1)
        expo[inp]++;
    for (auto x : expo)
    {
        integer *= power(x.first, x.second >> 1);
        if (x.second & 1)
            inroot *= x.first;
    }
    cout << integer << ' ' << inroot;
    return 0;
}
