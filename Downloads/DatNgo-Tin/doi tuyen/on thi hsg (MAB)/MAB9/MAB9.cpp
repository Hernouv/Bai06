#include <bits/stdc++.h>
using namespace std;

long long sum[1000010];

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB9.INP", "r", stdin);
    freopen("MAB9.OUT", "w", stdout);
    sum[0] = 0;
    for (long long i = 1; i <= 1000000; ++i)
        sum[i] = sum[i - 1] + i;
    int t;
    cin >> t;
    for (int i = 1; i <= t; ++i)
    {
        long long a, b;
        cin >> a >> b;
        a--;
        cout << sum[b] * sum[b] - sum[a] * sum[a] << '\n';
    }
    return 0;
}
