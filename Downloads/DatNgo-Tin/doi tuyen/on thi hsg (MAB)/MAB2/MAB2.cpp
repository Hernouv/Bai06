#include <bits/stdc++.h>
using namespace std;

bool erastos[10000010];
int prime[700010];

void sieve()
{
    memset(erastos, true, sizeof(erastos));
    for (int i = 2; i * i <= 10000000; ++i)
        if (erastos[i])
            for (int j = i * i; j <= 10000000; j += i)
                erastos[j] = false;

    int id = 1;
    for (int i = 2; i <= 10000000; ++i)
        if (erastos[i])
            prime[id++] = i;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB2.INP", "r", stdin);
    freopen("MAB2.OUT", "w", stdout);
    sieve();
    int a, b;
    cin >> a >> b;
    int lo = 1, hi;
    while (prime[lo] < a)
        lo++;
    hi = lo;
    while (prime[hi] <= b)
        hi++;
    hi--;
    cout << hi - lo + 1;
    return 0;
}
