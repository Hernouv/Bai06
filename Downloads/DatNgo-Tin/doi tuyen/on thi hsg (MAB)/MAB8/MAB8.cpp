#include <bits/stdc++.h>
using namespace std;

long long sumsq[100010];

void setVal()
{
    sumsq[1] = 1;
    for (long long i = 2; i <= 100000; ++i)
        sumsq[i] = sumsq[i - 1] + i * i;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB8.INP", "r", stdin);
    freopen("MAB8.OUT", "w", stdout);
    setVal();
    int t;
    cin >> t;
    for (int i = 1; i <= t; ++i)
    {
        int n;
        cin >> n;
        cout << sumsq[n] << '\n';
    }
    return 0;
}
