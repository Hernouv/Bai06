#include <bits/stdc++.h>
using namespace std;

bool check(long long num, long long q)
{
    long long ret = 0;
    while (num)
    {
        num /= 5;
        ret += num;
    }
    return (ret >= q);
}

long long search(long long in)
{
    if (in < 5)
        return in * 5;
    long long lo = 0, hi = 5 * in;
    while (lo < hi)
    {
        long long mid = (lo + hi) >> 1;
        if (check(mid, in))
            hi = mid;
        else
            lo = mid + 1;
    }
    return lo;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB10.INP", "r", stdin);
    freopen("MAB10.OUT", "w", stdout);
    long long k;
    cin >> k;
    cout << search(k);
    return 0;
}

