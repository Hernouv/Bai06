#include <bits/stdc++.h>
using namespace std;

bool friendly_num[100000];
bool check[100000];

int gcd(int a, int b)
{
    while (a and b)
    {
        if (a > b)
            a %= b;
        else
            b %= a;
    }
    return max(a, b);
}

int invert(int inp)
{
    string s = to_string(inp);
    string r;
    int sz = s.size() - 1;
    for (int i = 0; i <= sz; ++i)
        r += s[sz - i];
    int ret = stoi(r);
    return ret;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB3.INP", "r", stdin);
    freopen("MAB3.OUT", "w", stdout);
    for (int i = 1; i < 100000; ++i)
    {
        int inv = invert(i);
        if (gcd(i, inv) == 1)
        {
            friendly_num[i] = true;
            friendly_num[inv] = true;
        }
    }
    int a, b, cnt = 0;
    cin >> a >> b;
    for (int i = a; i <= b; ++i)
        if (friendly_num[i])
            cnt++;
    cout << cnt;
    return 0;
}
