#include <bits/stdc++.h>
using namespace std;

bool erastos[10000010];
int sumdigit[10000010];

void sieve()
{
    memset(erastos, true, sizeof(erastos));
    erastos[0] = erastos[1] = false;
    for (int i = 2; i * i <= 10000000; ++i)
        if (erastos[i])
            for (int j = i * i; j <= 10000000; j += i)
                erastos[j] = false;
}

void setVal()
{
    for (int i = 0; i <= 9; ++i)
        sumdigit[i] = i;
    for (int i = 10; i <= 10000000; ++i)
        sumdigit[i] = sumdigit[i / 10] + i % 10;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAB5.INP", "r", stdin);
    freopen("MAB5.OUT", "w", stdout);
    sieve();
    setVal();
    int a, b, cnt = 0;
    cin >> a >> b;
    for (int i = a; i <= b; ++i)
        if (erastos[sumdigit[i]])
            cnt++;
    cout << cnt;
    return 0;
}
