#include <bits/stdc++.h>
using namespace std;

int n, k, l = 1, start = 1, finish = 1, curr_len = 0;
int freq[1000010];
int arr[500010];

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("kgood.inp", "r", stdin);
    freopen("kgood.out", "w", stdout);
    memset(freq, 0, sizeof(freq));
    cin >> n >> k;
    for (int i = 1; i <= n; ++i)
        cin >> arr[i];
    for (int i = 1; i <= n; ++i)
    {
        freq[arr[i]]++;
        if (freq[arr[i]] == 1)
            curr_len++;
        while (curr_len > k)
        {
            freq[arr[l]]--;
            if (!freq[arr[l]])
                curr_len--;
            l++;
        }
        if (i - l + 1 > finish - start + 1)
            finish = i, start = l;
    }
    cout << start << ' ' << finish;
    return 0;
}
