#include <bits/stdc++.h>
using namespace std;

pair<int, int> tree_row[100010];
unordered_map<int, int> freq;
int n, m;

inline bool custom_arrange(pair<int, int> &a, pair<int, int> &b)
{
    return (a.first < b.first);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("mindis.inp", "r", stdin);
    freopen("mindis.out", "w", stdout);
    cin >> n >> m;
    for (int i = 1; i <= n; ++i)
    {
        int pos, type;
        cin >> pos >> type;
        tree_row[i] = {pos, type};
    }
    sort(tree_row + 1, tree_row + n + 1, custom_arrange);
    int l = 1, j = 1, curr_dis = 1e9 + 7;
    while (j <= n)
    {
        freq[tree_row[j].second]++;
        j++;
        if (freq.size() < m)
            continue;
        while (freq.size() == m)
        {
            if (curr_dis >= tree_row[j - 1].first - tree_row[l].first)
                curr_dis = tree_row[j - 1].first - tree_row[l].first;

            freq[tree_row[l].second]--;
            if (!freq[tree_row[l].second])
                freq.erase(tree_row[l].second);
            l++;
        }
    }
    cout << curr_dis;
    return 0;
}
