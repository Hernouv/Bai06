#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("evenodd.inp", "r", stdin);
    freopen("evenodd.out", "w", stdout);
    int n;
    int a, b;
    cin >> n;

    for (int i = 1; i <= n; ++i)
    {
        cin >> a >> b;
        if (a % 2 + b % 2 == 0)
            cout << "even";
        else
            cout << "odd";
        cout << '\n';
    }
    return 0;
}
