#include <bits/stdc++.h>
using namespace std;

bool bridge[100010];
int way[100010];
const int mod = 26051968;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("treasure.inp", "r", stdin);
    freopen("treasure.out", "w", stdout);
    memset(way, 0, sizeof(way));
    way[1] = 1;
    int n, k;
    cin >> n >> k;
    for (int i = 0; i <= n; ++i)
        bridge[i] = true;
    bool invalid = false;
    for (int i = 1; i <= k; ++i)
    {
        int pos, newpos = 1e9, oldpos = 1e9;
        cin >> pos;
        newpos = pos;
        if (newpos - oldpos == 1)
        {
            invalid = true;
            break;
        }
        bridge[pos] = false;
        oldpos = pos;
    }
    if (invalid)
        cout << 0;
    else
    {
        way[0] = 1;
        for (int i = 2; i <= n; ++i)
        {
            if (bridge[i])
            {
                if (bridge[i - 1])
                    way[i] = (way[i - 1] + way[i - 2]) % mod;
                else
                    way[i] = way[i - 2];
            }
        }
        cout << way[n];
    }
    return 0;
}
