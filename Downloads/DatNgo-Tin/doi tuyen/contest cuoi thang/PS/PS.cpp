#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("PS.INP", "r", stdin);
    freopen("PS.OUT", "w", stdout);
    int n;
    while (cin >> n)
    {
        int exp = 0;
        for (int i = 0; i < 25; ++i)
            exp += (n >> i) & 1;
        cout << pow(2, exp) << '\n';
    }
    return 0;
}
