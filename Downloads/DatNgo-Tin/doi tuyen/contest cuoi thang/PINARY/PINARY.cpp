#include <bits/stdc++.h>
using namespace std;

#define ll long long
ll fib[41], sumfib[41], exclusive[3] = {0, 1, 10};
void setVal()
{
    fib[0] = sumfib[0] = 0, fib[1] = sumfib[1] = 1;
    for (ll i = 2; i <= 40; ++i)
    {
        fib[i] = fib[i - 1] + fib[i - 2];
        sumfib[i] = sumfib[i - 1] + fib[i];
    }
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("PINARY.INP", "r", stdin);
    freopen("PINARY.OUT", "w", stdout);
    setVal();
    ll n;
    while (cin >> n)
    {
        if (n < 2)
            cout << exclusive[n] << '\n';
        else
        {
            ll it = 0;
            while (sumfib[it] < n)
                it++;
            while (it > 2 and n > 2)
            {
                cout << 10;
                ll x_th = n - sumfib[it - 1] - 1;
                n = x_th;
                int sz = 0;
                while (sumfib[sz] < n)
                    sz++;
                it -= 2;
                while (it > sz)
                {
                    cout << 0;
                    it--;
                }
            }
            if (n > 0)
                cout << exclusive[n];
            cout << '\n';
        }
    }
    return 0;
}
