#include <bits/stdc++.h>
using namespace std;

#define ull unsigned long long
const ull mod = 1e9 + 7;
ull arr[1010], res = 0;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("SUMKSET.INP", "r", stdin);
    freopen("SUMKSET.OUT", "w", stdout);
    ull n, k;
    cin >> n >> k;
    for (int i = 1; i <= n; ++i)
        cin >> arr[i];
    sort(arr + 1, arr + n + 1);
    for (int i = k; i <= n; ++i)
    {
        ull t1 = i - 1, t2 = i - 2;
        ull mul = (t1 * t2) >> 1;
        mul %= mod;
        mul *= arr[i];
        res += mul % mod;
        res %= mod;
    }
    cout << res;
    return 0;
}
