#include <bits/stdc++.h>
using namespace std;

map<int, int> cc; // connected component
vector<int> graph[1000];
bool visited[1010], origin;

void dfs(int start, int origin)
{
    visited[start] = true;
    for (auto v : graph[start])
    {
        if (!visited[v])
        {
            cc[origin] += v;
            dfs(v, origin);
        }
    }
}

void maxi(int &a, int b)
{
    if (a < b)
        a = b;
    return;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("DFSSMAX.INP", "r", stdin);
    freopen("DFSSMAX.OUT", "w", stdout);
    int n, m;
    cin >> n >> m;
    for (int i = 1; i <= m; ++i)
    {
        int u, v;
        cin >> u >> v;
        graph[u].push_back(v);
        graph[v].push_back(u);
    }
    for (int i = 1; i <= n; ++i)
        if (!visited[i])
        {
            cc[i] += i;
            dfs(i, i);
        }
    int rmax = 0;
    for (auto it : cc)
        maxi(rmax, it.second);
    cout << rmax;
    return 0;
}
