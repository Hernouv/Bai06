#include <bits/stdc++.h>
using namespace std;

#define ull unsigned long long
map<ull, bool> fibonacci;
ull fib[2] = {0, 1};
ull arr[100010];
ull sum = 0;
int n, k, res = 0;

void setVal()
{
    int it = 0, cnt = 1;
    while (cnt < 91)
    {
        fib[it] = fib[it] + fib[1 - it];
        fibonacci[fib[it]] = true;
        it = 1 - it;
        cnt++;
    }
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("FIBO.INP", "r", stdin);
    freopen("FIBO.OUT", "w", stdout);
    setVal();
    cin >> n >> k;
    arr[0] = 0;
    for (int i = 1; i <= n; ++i)
        cin >> arr[i];
    for (int i = 0; i < k; ++i)
        sum += arr[i];
    for (int i = k; i <= n; ++i)
    {
        sum = sum - arr[i - k] + arr[i];
        if (fibonacci[sum])
            res++;
    }
    cout << res;
    return 0;
}
