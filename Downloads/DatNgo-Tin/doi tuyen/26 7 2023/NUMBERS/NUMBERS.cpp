#include <bits/stdc++.h>
using namespace std;
int n, k, p;
int ele[1000010], total[1000010];
bool check(int u)
{
    string str_u = to_string(u);
    string chr_k = to_string(k);
    for (int i = 0; i < str_u.size(); ++i)
        if (str_u[i] != '0' and str_u[i] != chr_k[0])
            return false;
    return true;
}
void process(int u)
{
    for (int i = 1; i <= u; i++)
        if (!check(ele[i]))
            return;
    p = 1;
    for (int i = 1; i <= u - 1; i++)
        cout
            << ele[i] << "+";
    cout << ele[u] << endl;
}

void permutation(int i)
{
    for (int j = ele[i - 1]; 2 * j <= n - total[i - 1]; j++)
    {
        ele[i] = j;
        total[i] = total[i - 1] + j;
        permutation(i + 1);
    }
    ele[i] = n - total[i - 1];
    process(i);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("NUMBERS.INP", "r", stdin);
    freopen("NUMBERS.OUT", "w", stdout);
    while (cin >> n >> k)
    {
        p = 0;
        ele[0] = 1;
        total[0] = 0;
        permutation(1);
        if (p == 0)
            cout << -1 << endl;
    }
    return 0;
}
