#include <bits/stdc++.h>
using namespace std;

const int nmax = 1000010;
int sumdigit[nmax], cntdigit[nmax], beauty[100010];

void preprocess()
{
    for (int i = 0; i <= 5; ++i)
    {
        int lo = pow(10, i), hi = pow(10, i + 1);
        for (int j = lo; j < hi; ++j)
            cntdigit[j] = i + 1;
        cntdigit[1000000] = 7;

        for (int i = 0; i < 10; ++i)
            sumdigit[i] = i;
        for (int i = 10; i <= 1000000; ++i)
            sumdigit[i] = sumdigit[i / 10] + i % 10;
    }
    int id = 0, iter = 1;
    while (id < 100000)
    {
        if (sumdigit[iter] % cntdigit[iter] == 0)
            beauty[++id] = iter;
        iter++;
    }
}

int main()
{
    freopen("BEAUTY.INP", "r", stdin);
    freopen("BEAUTY.OUT", "w", stdout);
    cin.tie(0)->sync_with_stdio(false);
    preprocess();
    int n;
    while (cin >> n)
        cout << beauty[n] << '\n';
    return 0;
}
