#include <bits/stdc++.h>
using namespace std;

int gcd(int a, int b)
{
    if (b == 0)
        return a;
    return gcd(b, a % b);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("COMDIV.INP", "r", stdin);
    freopen("COMDIV.OUT", "w", stdout);
    int n;
    cin >> n;
    vector<int> line(n + 1);
    line[0] = 1;
    for (int i = 1; i <= n; i++)
        line[i] = line[i - 1] * (n - i + 1) / i;

    int result = 0;
    for (int i = 0; i <= n; i++)
        if (line[i] > 1)
            result = gcd(result, line[i]);

    cout << result << endl;
    return 0;
}
