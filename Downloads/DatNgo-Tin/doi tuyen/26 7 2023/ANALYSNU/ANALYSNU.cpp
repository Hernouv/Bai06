#include <bits/stdc++.h>
using namespace std;

int a[100000], t[100000], n, cnt = 0;
bool erastos[1000010];
void sieve(int u)
{
    for (int i = 2; i <= u; ++i)
        erastos[i] = true;
    for (int i = 2; i * i <= u; ++i)
        if (erastos[i])
            for (int j = i * i; j <= u; j += i)
                erastos[j] = false;
}

void process(int u)
{
    for (int i = 1; i < u; ++i)
    {
        if (a[i] == a[i + 1])
            return;
        else if (!erastos[a[i]])
            return;
    }
    if (!erastos[a[u]])
        return;
    for (int i = 1; i <= u; ++i)
        cout << a[i] << ' ';
    cout << '\n';
    cnt++;
}

void analy(int i)
{
    // variable j: assigning value to each element in the array
    // also iterator :>
    for (int j = a[i - 1]; 2 * j <= n - t[i - 1]; ++j)
    {
        a[i] = j;
        t[i] = t[i - 1] + a[i];
        analy(i + 1);
    }
    a[i] = n - t[i - 1];
    process(i);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    // freopen("ANALYSNU.INP", "r", stdin);
    // freopen("ANALYSNU.OUT", "w", stdout);
    cin >> n;
    sieve(n);
    a[0] = 1;
    t[0] = 0;
    analy(1);
    cout << cnt;
    return 0;
}
