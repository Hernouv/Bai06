#include <bits/stdc++.h>
using namespace std;

bool erastos[1000001];
int fib[32];

void sieve()
{
    memset(erastos, true, sizeof(erastos));
    erastos[0] = erastos[1] = false;
    for (int i = 2; i <= 1000; ++i)
        if (erastos[i])
            for (int j = i * i; j <= 1000000; j += i)
                erastos[j] = false;
}

void setfib()
{
    fib[0] = 0, fib[1] = 1;
    for (int i = 2; i < 32; ++i)
        fib[i] = fib[i - 1] + fib[i - 2];
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("FIBPRIME.INP", "r", stdin);
    freopen("FIBPRIME.OUT", "w", stdout);
    sieve();
    setfib();
    int lo, hi;
    cin >> lo >> hi;
    int start = 1, end = 31, cnt = 0;
    while (fib[start] < lo)
        start++;
    while (fib[end] > hi)
        end--;
    for (int i = start; i <= end; ++i)
        if (erastos[fib[i]])
            cnt++;
    cout << cnt;
    return 0;
}
