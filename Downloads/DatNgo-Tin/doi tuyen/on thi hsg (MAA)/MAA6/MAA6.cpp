#include <bits/stdc++.h>
using namespace std;

long long a, b, c, d, cd, lo, hi, loc, hic, lod, hid;

long long gcd(long long c, long long d)
{
    while (c and d)
    {
        if (c > d)
            c %= d;
        else
            d %= c;
    }
    return max(c, d);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA6.INP", "r", stdin);
    freopen("MAA6.OUT", "w", stdout);
    cin >> a >> b >> c >> d;
    cd = c * d;
    cd /= gcd(c, d);
    lo = ceil(double(a) / cd);
    hi = b / cd;
    cout << hi - lo + 1;
    return 0;
}
