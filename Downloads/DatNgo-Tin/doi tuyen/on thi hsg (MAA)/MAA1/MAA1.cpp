#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA1.INP", "r", stdin);
    freopen("MAA1.OUT", "w", stdout);
    long long n;
    int cnt = 0;
    cin >> n;
    for (long long i = 1; i * i <= n; ++i)
    {
        if (n % i == 0)
        {
            cnt++;
            if (i != n / i)
                cnt++;
        }
    }
    cout << cnt;
    return 0;
}
