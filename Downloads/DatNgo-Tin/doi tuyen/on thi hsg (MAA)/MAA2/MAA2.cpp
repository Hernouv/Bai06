#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA2.INP", "r", stdin);
    freopen("MAA2.OUT", "w", stdout);
    long long sum = 0, n;
    cin >> n;
    for (long long i = 1; i * i <= n; ++i)
    {
        if (n % i == 0)
        {
            sum += i;
            long long par = n / i;
            if (i != par)
                sum += par;
        }
    }
    cout << sum;
    return 0;
}
