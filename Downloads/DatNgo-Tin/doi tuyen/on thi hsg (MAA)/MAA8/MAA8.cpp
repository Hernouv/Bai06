#include <bits/stdc++.h>
using namespace std;

long long pwrmod(long long base, long long exp, long long mod)
{
    if (!exp)
        return 1;
    long long t = pwrmod(base, exp >> 1, mod);
    t = (t * t) % mod;
    if (exp & 1)
        t = (t * base) % mod;
    return t;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA8.INP", "r", stdin);
    freopen("MAA8.OUT", "w", stdout);
    long long base, exp, mod;
    cin >> base >> exp >> mod;
    cout << pwrmod(base, exp, mod);
    return 0;
}
