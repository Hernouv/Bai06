#include <bits/stdc++.h>
using namespace std;

vector<int> mod[10];

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA9.INP", "r", stdin);
    freopen("MAA9.OUT", "w", stdout);
    mod[0] = {0, 0, 0, 0};
    mod[1] = {1, 1, 1, 1};
    mod[2] = {6, 2, 4, 8};
    mod[3] = {1, 3, 9, 7};
    mod[4] = {6, 4, 6, 4};
    mod[5] = {5, 5, 5, 5};
    mod[6] = {6, 6, 6, 6};
    mod[7] = {1, 7, 9, 3};
    mod[8] = {6, 8, 4, 2};
    mod[9] = {1, 9, 1, 9};
    string a, b;
    cin >> a >> b;
    b = '0' + b;
    int ia, ib;
    ia = a[a.size() - 1] - '0';
    ib = (b[b.size() - 1] - '0') + (b[b.size() - 2] - '0') * 10;
    ib %= 4;
    cout << mod[ia][ib];
    return 0;
}
