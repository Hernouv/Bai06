#include <bits/stdc++.h>
using namespace std;

long long gcd(long long a, long long b)
{
    while (a and b)
    {
        if (a < b)
            swap(a, b);
        a %= b;
    }
    return max(a, b);
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA3.INP", "r", stdin);
    freopen("MAA3.OUT", "w", stdout);
    long long a, b;
    cin >> a >> b;
    cout << gcd(a, b);
    return 0;
}
