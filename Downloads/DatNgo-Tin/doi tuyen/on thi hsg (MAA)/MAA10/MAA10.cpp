#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("MAA10.INP", "r", stdin);
    freopen("MAA10.OUT", "w", stdout);
    long long a, b;
    cin >> a >> b;
    a--;
    long long lo = a * (a + 1) / 2, hi = b * (b + 1) / 2;
    cout << hi - lo;
    return 0;
}
