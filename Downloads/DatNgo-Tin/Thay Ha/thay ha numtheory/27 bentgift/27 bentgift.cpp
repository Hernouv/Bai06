#include <bits/stdc++.h>
using namespace std;

bool sold[1000010];
bool gift[1000010];
int from[1000010];

void setVal()
{
    for (int i = 0; i < 1000010; ++i)
        from[i] = i;
}

void process()
{
    int m;
    cin >> m;
    for (int i = 1; i <= m; ++i)
    {
        int pos;
        cin >> pos;
        gift[pos] = true;
    }
    int n;
    cin >> n;
    for (int i = 1; i <= n; ++i)
    {
        int rq;
        cin >> rq;
        int cnt = rq;
        while (from[rq] <= 1000000 and cnt)
        {
            if (!sold[from[rq]])
            {
                cnt--;
                sold[from[rq]] = true;
                from[rq] += rq;
            }
            else
            {
                from[rq] += rq;
            }
        }
    }
    int res = 0;
    for (int i = 1; i <= 1000000; ++i)
        if (gift[i] and sold[i])
            res++;
    cout << res;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("bentgift.inp", "r", stdin);
    freopen("bentgift.out", "w", stdout);
    setVal();
    process();
    return 0;
}
