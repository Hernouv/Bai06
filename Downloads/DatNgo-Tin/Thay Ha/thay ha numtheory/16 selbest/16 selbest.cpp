#include <bits/stdc++.h>
using namespace std;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("selbest.inp", "r", stdin);
    freopen("selbest.out", "w", stdout);

    int rq, n, a[3];
    cin >> rq;
    cin >> n >> a[0] >> a[1] >> a[2];
    sort(a, a + 3);
    if (rq == 2)
        cout << a[0];
    else if (rq == 1)
    {
        int sum = a[0] + a[1];
        if (sum <= n)
            cout << 0;
        else
        {
            int overlap = sum - n;
            n -= overlap;
            cout << a[2] - n;
        }
    }

    return 0;
}
