#include <bits/stdc++.h>
using namespace std;

#define ll long long
const ll mod = 1e9 + 7;
ll arr[100010];
ll numdigicnt[100010];
ll digicnt[10];
ll uppercnt = 0, res = 0;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    freopen("ccatsum.inp", "r", stdin);
    freopen("ccatsum.out", "w", stdout);

    memset(digicnt, 0, sizeof(digicnt));
    ll n;
    cin >> n;
    for (int i = 1; i <= n; ++i)
    {
        cin >> arr[i];
        ll sz = ceil(log10(arr[i]));
        numdigicnt[i] = sz;
        digicnt[sz]++;
    }
    for (int i = 1; i <= 9; ++i)
        uppercnt += i * pow(10, i);
    for (int i = 1; i <= n; ++i)
    {
        res += arr[i];
        res %= mod;
    }

    return 0;
}
