#include <bits/stdc++.h>
using namespace std;

long long erastos[200010];
long long signaVal[200010];
long long res = 0;
unordered_map<long long, long long> signa_cnt;

void sieve()
{
    for (int i = 0; i <= 200000; ++i)
        erastos[i] = i;
    for (int i = 2; i * i <= 200000; ++i)
        if (erastos[i] == i)
            for (int j = i * i; j <= 200000; j += i)
                erastos[j] = i;
}

void process(long long lim)
{
    for (int i = 1; i <= lim; ++i)
        signaVal[i] = 1;
    signa_cnt[1]++;
    for (int i = 2; i <= lim; ++i)
    {
        long long t = i;
        while (t > 1)
        {
            long long pr = erastos[t], exp = 0;
            while (t % pr == 0)
            {
                exp++;
                t /= pr;
            }
            if (exp & 1)
                signaVal[i] *= pr;
        }
        signa_cnt[signaVal[i]]++;
    }
    for (auto x : signa_cnt)
    {
        if (x.second > 2)
        {
            long long num = x.second;
            res += num * (num - 1) * (num - 2) / 6;
        }
    }
    cout << res;
}

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    sieve();
    long long n;
    cin >> n;
    process(n);
    return 0;
}
