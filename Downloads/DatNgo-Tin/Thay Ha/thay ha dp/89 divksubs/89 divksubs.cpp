#include <bits/stdc++.h>
using namespace std;

int arr[2001], dp[2001][1000];
const int mod = 1e8;

int main()
{
    cin.tie(0)->sync_with_stdio(false);
    memset(dp, false, sizeof(dp));
    int n, m, t;
    cin >> n >> m;
    for (int i = 1; i <= n; ++i)
    {
        cin >> arr[i];
        arr[i] %= m;
    }
    for (int i = 1; i <= n; ++i)
    {
        for (int j = 0; j < m; ++j)
        {
            t = i - 1;
            dp[i][j] = (dp[t][j] + dp[t][(j - arr[i] + m) % m]) % mod;
        }
        dp[i][arr[i]]++;
    }
    cout << dp[n][0];
    return 0;
}
